package wire

import (
	"bytes"
	"math"
	"testing"

	"google.golang.org/protobuf/encoding/protowire"
	"google.golang.org/protobuf/proto"
	networkpb "ucupa/shared/bindings/go/protobuf"
	"ucupa/shared/values"
	corepb "ucupa/ucupa-core/bindings/go/protobuf"
)

func TestRepresentationPreservesPresenceAndEquivalentWire(t *testing.T) {
	p := &corepb.ReadElementRequest{Handle: &networkpb.Token{Owner: proto.String("00000000-0000-4000-8000-000000000001"), Kind: networkpb.TokenKind_SPACE_HANDLE.Enum(), Value: make([]byte, 32)}, Address: &networkpb.Address{}}
	a, err := ToValue(p.ProtoReflect(), 0)
	if err != nil {
		t.Fatal(err)
	}
	raw, err := values.CanonicalJSONValue(a)
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Contains(raw, []byte("prepareObserve")) || bytes.Contains(raw, []byte("down")) {
		t.Fatal("absent optional fields filled")
	}
	p.PrepareObserve = proto.Bool(false)
	p.Address.Down = &networkpb.ElementPath{}
	a, err = ToValue(p.ProtoReflect(), 0)
	if err != nil {
		t.Fatal(err)
	}
	raw, err = values.CanonicalJSONValue(a)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(raw, []byte(`"prepareObserve":false`)) || !bytes.Contains(raw, []byte(`"down":[]`)) {
		t.Fatal("explicit empty/false omitted")
	}
	wire, err := proto.Marshal(p)
	if err != nil {
		t.Fatal(err)
	}
	var parts [][]byte
	for len(wire) > 0 {
		_, _, n := protowire.ConsumeField(wire)
		if n < 0 {
			t.Fatal("bad generated bytes")
		}
		parts = append(parts, bytes.Clone(wire[:n]))
		wire = wire[n:]
	}
	for i := len(parts) - 1; i >= 0; i-- {
		wire = append(wire, parts[i]...)
	}
	var decoded corepb.ReadElementRequest
	if err := proto.Unmarshal(wire, &decoded); err != nil {
		t.Fatal(err)
	}
	v, e := ToValue(decoded.ProtoReflect(), 0)
	if e != nil {
		t.Fatal(e)
	}
	reordered, e := values.CanonicalJSONValue(v)
	if e != nil || !bytes.Equal(raw, reordered) {
		t.Fatal("wire order changed operation")
	}
}

func TestRepresentationRejectsInvalidInputs(t *testing.T) {
	inputs := []proto.Message{
		&corepb.EnterRequest{},
		&corepb.ReleaseObserveRequest{},
		&corepb.MutationCommand{},
		&corepb.Sphere{Center: &networkpb.Vector3{Items: []float64{0, 0, 0}}, Radius: proto.Float64(math.NaN())},
		&networkpb.Vector3{Items: []float64{0, 0}},
		&corepb.EnterRequest{Reference: &networkpb.Reference{}, Intent: corepb.Intent(999).Enum()},
	}
	for _, in := range inputs {
		if _, err := ToValue(in.ProtoReflect(), 0); err == nil {
			t.Errorf("accepted %T", in)
		}
	}
	in := &networkpb.Address{}
	in.ProtoReflect().SetUnknown([]byte{0x98, 0x06, 0x01})
	if _, err := ToValue(in.ProtoReflect(), 0); err == nil {
		t.Fatal("unknown nested fields accepted")
	}
}
