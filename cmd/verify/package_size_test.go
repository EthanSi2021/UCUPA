func TestPackageSizeUsesDirectDirectoriesAndSeparateClasses(t *testing.T) {
	packages := map[string]packageSize{}
	countPackageSource(packages, "ucupa-core/internal/query/query.go", []byte("package query\n"))
	countPackageSource(packages, "ucupa-core/internal/query/query_test.go", []byte("package query_test\n"))
	countPackageSource(packages, "ucupa-core/internal/query/fact/view.go", []byte("package fact\n"))
	countPackageSource(packages, "ucupa-core/bindings/go/protobuf/core.pb.go", []byte("package protobuf\n"))
	got := packages["ucupa-core/internal/query"]
	if got.production != (sourceSize{1, 1}) || got.tests != (sourceSize{1, 1}) || got.generated != (sourceSize{}) {
		t.Fatalf("query direct package: %+v", got)
	}
	if len(packages) != 3 || packages["ucupa-core/bindings/go/protobuf"].generated != (sourceSize{1, 1}) {
		t.Fatalf("descendants or binding classes merged: %+v", packages)
	}
}

func TestPackageProductionLimitsApplyOutsideModuleRoots(t *testing.T) {
	for _, dir := range []string{"ucupa-core/internal/query", "ucupa-facet/transport/grpc", "ucupa-core/sdk/go", "cmd/unreviewed"} {
		for _, tc := range []struct {
			size   sourceSize
			count  int
			review bool
		}{
			{sourceSize{25, 5000}, 0, false},
			{sourceSize{26, 100}, 1, true},
			{sourceSize{1, 5001}, 1, true},
			{sourceSize{50, 10000}, 1, true},
			{sourceSize{51, 100}, 1, false},
			{sourceSize{1, 10001}, 1, false},
		} {
			got := checkProductionSize(dir, tc.size)
			if len(got) != tc.count || len(got) > 0 && got[0].review != tc.review {
				t.Errorf("%s %+v: %v", dir, tc.size, got)
			}
		}
	}
}

func TestPackageTestReviewAndFiniteAllowances(t *testing.T) {
	for _, size := range []sourceSize{{51, 10}, {1, 10001}} {
		got := checkTestSize("ucupa-facet/internal/namespace", size)
		if len(got) != 1 || !got[0].review {
			t.Fatalf("missing test responsibility review: %v", got)
		}
	}
	if got := checkTestSize("ucupa-facet/internal/namespace", sourceSize{50, 10000}); len(got) != 0 {
		t.Fatalf("exact test limit: %v", got)
	}
	for dir, allowance := range productionAllowances {
		if allowance.reason == "" || len(checkProductionSize(dir, allowance.maximum)) != 0 {
			t.Fatalf("invalid production allowance: %s", dir)
		}
		for _, size := range []sourceSize{{allowance.maximum.files + 1, 1}, {1, allowance.maximum.lines + 1}} {
			got := checkProductionSize(dir, size)
			if len(got) != 1 || got[0].review {
				t.Fatalf("unbounded production allowance: %s %+v %v", dir, size, got)
			}
		}
	}
	for dir, allowance := range testAllowances {
		if allowance.reason == "" || len(checkTestSize(dir, allowance.maximum)) != 0 {
			t.Fatalf("invalid test allowance: %s", dir)
		}
		for _, size := range []sourceSize{{allowance.maximum.files + 1, 1}, {1, allowance.maximum.lines + 1}} {
			got := checkTestSize(dir, size)
			if len(got) != 1 || got[0].review {
				t.Fatalf("unbounded test allowance: %s %+v %v", dir, size, got)
			}
		}
	}
}

func TestPackageSizeCannotHideInInactiveOrUnregisteredGeneratedFiles(t *testing.T) {
	root := fixture(t)
	files := productionAllowances["ucupa-facet/internal/namespace"].maximum.files + 1
	for i := 0; i < files; i++ {
		name := fmt.Sprintf("ucupa-facet/internal/namespace/file_%02d.go", i)
		writeFixture(t, root, name, "//go:build inactive\n\n// Code generated by fake. DO NOT EDIT.\n\npackage namespace\n")
	}
	issues := checkRepository(root, testStdlib())
	assertIssue(t, issues, "ucupa-facet/internal/namespace", fmt.Sprintf("%d files", files), false)
	assertIssue(t, issues, "ucupa-facet/internal/namespace/file_00.go", "generated source is not approved", false)
	data := []byte("package sample\n\n" + strings.Repeat("// physical line\n", 20))
	packages := map[string]packageSize{}
	countPackageSource(packages, "ucupa-core/internal/element/input.go", data)
	if packages["ucupa-core/internal/element"].production.lines != 22 {
		t.Fatal("package statistics excluded comments or blank lines")
	}
}
