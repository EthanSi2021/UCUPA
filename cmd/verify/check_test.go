func TestCompletedModuleRootsCannotRegainCodeOrImports(t *testing.T) {
	for _, owner := range []string{"ucupa-core", "ucupa-facet"} {
		for _, name := range []string{"new.go", "regression_test.go", "adapter.go", "inactive.go"} {
			file := owner + "/" + name
			data := "//go:build never_enabled\n\npackage oldroot\n"
			assertIssue(t, checkSource(file, []byte(data), "ucupa", testStdlib()), file, "root is navigation only", false)
		}
		for _, source := range []string{"composition/cluster.go", "cmd/ucupa/main.go", "acceptance/connected_fixture_test.go", "ucupa-core/contract/spatial.go", "ucupa-core/internal/element/operation.go", "ucupa-core/transport/grpc/server.go", "ucupa-facet/sdk/go/client.go"} {
			if got := checkDependency(source, "ucupa/"+owner, "ucupa", strings.HasSuffix(source, "_test.go"), testStdlib()); got == "" {
				t.Error("old root remains an importable entry", source, owner)
			}
		}
		if len(checkProductionSize(owner, sourceSize{})) != 0 || len(checkTestSize(owner, sourceSize{})) != 0 {
			t.Error("empty module navigation rejected", owner)
		}
		for _, result := range [][]issue{checkProductionSize(owner, sourceSize{1, 1}), checkTestSize(owner, sourceSize{1, 1})} {
			if len(result) != 1 || result[0].review {
				t.Error("root regained file-count headroom", owner, result)
			}
		}
	}
	for _, tc := range []struct{ file, imported string }{
		{"composition/cluster.go", "ucupa/ucupa-core/instance"},
		{"cmd/ucupa/connected.go", "ucupa/ucupa-core/instance"},
		{"acceptance/connected_fixture_test.go", "ucupa/ucupa-core/instance"},
		{"ucupa-core/sdk/go/client.go", "ucupa/ucupa-core/contract"},
	} {
		if got := checkDependency(tc.file, tc.imported, "ucupa", strings.HasSuffix(tc.file, "_test.go"), testStdlib()); got != "" {
			t.Error("actual public entry rejected", tc, got)
		}
	}
}

func TestValidationGatesAreExplicitAndNonMutating(t *testing.T) {
	gates := validationGates("selected-go")
	want := [][]string{
		{"run", "./cmd/protogen", "-check"},
		{"test", "./...", "-count=1", "-timeout=20m"},
		{"test", "-race", "./...", "-count=1", "-timeout=20m"},
		{"vet", "./..."},
		{"mod", "tidy", "-diff"},
		{"run", "./cmd/ucupa"},
		{"diff", "--check"},
	}
	if len(gates) != len(want) {
		t.Fatalf("gates=%v", gates)
	}
	for i, gate := range gates {
		if !reflect.DeepEqual(gate.args, want[i]) || gate.race != (i == 2) {
			t.Fatalf("gate %d: %+v", i, gate)
		}
		if i < 6 && gate.program != "selected-go" {
			t.Fatalf("Go selection lost: %+v", gate)
		}
	}
	t.Setenv("GOFLAGS", "-run=NotTheWholeSuite")
	t.Setenv("GOWORK", "external-workspace")
	t.Setenv("CGO_ENABLED", "0")
	values := map[string]string{}
	for _, item := range commandEnvironment(true) {
		key, value, _ := strings.Cut(item, "=")
		if key == "" {
			// Windows per-drive directory pseudo-variables ("=C:=...") carry no
			// real environment key and must not count as duplicates.
			continue
		}
		key = strings.ToUpper(key)
		if _, duplicate := values[key]; duplicate {
			t.Fatalf("duplicate environment key: %s", key)
		}
		values[key] = value
	}
	if values["CGO_ENABLED"] != "1" || values["GOWORK"] != "off" || values["GOFLAGS"] != " " {
		t.Fatalf("required gate environment not applied: CGO_ENABLED=%q GOWORK=%q GOFLAGS=%q", values["CGO_ENABLED"], values["GOWORK"], values["GOFLAGS"])
	}
}

func fixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeFixture(t, root, "go.mod", "module ucupa\n\ngo 1.25.0\n")
	writeFixture(t, root, "go.sum", "")
	return root
}

func writeFixture(t *testing.T, root, name, data string) {
	t.Helper()
	file := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(file), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(file, []byte(data), 0o600); err != nil {
		t.Fatal(err)
	}
}

func testStdlib() map[string]bool {
	return map[string]bool{"fmt": true, "os": true, "testing": true}
}

func assertIssue(t *testing.T, issues []issue, file, message string, review bool) {
	t.Helper()
	for _, item := range issues {
		if item.path == file && strings.Contains(item.message, message) && item.review == review {
			return
		}
	}
	t.Fatalf("missing issue %s %q review=%v in %v", file, message, review, issues)
}

