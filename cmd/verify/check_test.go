func TestGeneratedMarkerDoesNotBypassLimits(t *testing.T) {
	data := "// Code generated by imaginary-tool. DO NOT EDIT.\n\npackage sample\n\n" + strings.Repeat("// line\n", 800)
	issues := checkSource("ucupa-core/generated.go", []byte(data), "ucupa", testStdlib())
	assertIssue(t, issues, "ucupa-core/generated.go", "generated source is not approved", false)
	assertIssue(t, issues, "ucupa-core/generated.go", "hard limit 800", false)
	directive := "package sample\n\n//go:generate imaginary-tool\n"
	assertIssue(t, checkSource("ucupa-core/generate.go", []byte(directive), "ucupa", testStdlib()), "ucupa-core/generate.go", "go:generate is not approved", false)
	// A marker in a test's string fixture is data, not a generation declaration.
	literal := "package sample\n\nconst fixture = \"// Code generated by fake. DO NOT EDIT.\\n//go:generate fake\"\n"
	if got := checkSource("cmd/size-sample/generated_test.go", []byte(literal), "ucupa", testStdlib()); len(got) != 0 {
		t.Fatalf("fixture string mistaken for generated source: %v", got)
	}
}

func TestModuleBoundaries(t *testing.T) {
	cases := []struct{ name, file, data, message string }{
		{"nested module", "ucupa-core/go.mod", "module nested\n", "nested module"},
		{"nested sum", "ucupa-core/go.sum", "", "nested module"},
		{"workspace", "go.work", "go 1.25.0\n", "workspace files"},
		{"nested workspace sum", "nested/go.work.sum", "", "workspace files"},
		{"replace", "go.mod", "module ucupa\nreplace example.com/a => ../a\n", "replace directives"},
		{"replace block", "go.mod", "module ucupa\nreplace (\nexample.com/a => ../a\n)\n", "replace directives"},
		{"wrong module", "go.mod", "module something-else\n", "single root module ucupa"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			root := fixture(t)
			writeFixture(t, root, tc.file, tc.data)
			assertIssue(t, checkRepository(root, testStdlib()), tc.file, tc.message, false)
		})
	}
	root := fixture(t)
	if err := os.Remove(filepath.Join(root, "go.sum")); err != nil {
		t.Fatal(err)
	}
	assertIssue(t, checkRepository(root, testStdlib()), "go.sum", "required root module file", false)
	_, issues := checkModule([]byte("module ucupa\n// replace examples are comments\n"))
	if len(issues) != 0 {
		t.Fatalf("comment is not a replace directive: %v", issues)
	}
}

