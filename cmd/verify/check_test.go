func TestRepositoryChecksIncludeUntrackedSourceAndSkipGit(t *testing.T) {
	root := fixture(t)
	writeFixture(t, root, ".git/ignored.go", "not Go source")
	writeFixture(t, root, "cmd/new/main.go", "package main\n\nfunc main() {}\n")
	if issues := checkRepository(root, testStdlib()); len(issues) != 0 {
		t.Fatalf("clean untracked fixture: %v", issues)
	}
	writeFixture(t, root, "ucupa-core/new.go", "package core\n\nimport _ \"ucupa/ucupa-facet/instance\"\n")
	issues := checkRepository(root, testStdlib())
	assertIssue(t, issues, "ucupa-core/new.go", "another owner", false)
	for _, item := range issues {
		if strings.HasPrefix(item.path, ".git/") {
			t.Fatalf("scanned .git: %v", item)
		}
	}
}

func TestFileLimitsUseFormattedPhysicalLines(t *testing.T) {
	cases := []struct {
		name, file string
		lines      int
		message    string
		review     bool
	}{
		{"production at review", "cmd/size-sample/sample.go", 500, "", false},
		{"production review", "cmd/size-sample/sample.go", 501, "501 physical lines", true},
		{"production at hard", "cmd/size-sample/sample.go", 800, "800 physical lines", true},
		{"production hard", "cmd/size-sample/sample.go", 801, "hard limit 800", false},
		{"test at review", "cmd/size-sample/sample_test.go", 800, "", false},
		{"test review", "cmd/size-sample/sample_test.go", 801, "801 physical lines", true},
		{"test at hard", "cmd/size-sample/sample_test.go", 1000, "1000 physical lines", true},
		{"test hard", "cmd/size-sample/sample_test.go", 1001, "hard limit 1000", false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			data := []byte("package sample\n\n" + strings.Repeat("// line\n", tc.lines-2))
			issues := checkSource(tc.file, data, "ucupa", testStdlib())
			if tc.message == "" {
				if len(issues) != 0 {
					t.Fatalf("at threshold: %v", issues)
				}
			} else {
				assertIssue(t, issues, tc.file, tc.message, tc.review)
				if len(issues) != 1 {
					t.Fatalf("unexpected issues: %v", issues)
				}
			}
		})
	}
	if physicalLines(nil) != 0 || physicalLines([]byte("one")) != 1 || physicalLines([]byte("one\n\n")) != 2 {
		t.Fatal("physical line counting changed")
	}
}

